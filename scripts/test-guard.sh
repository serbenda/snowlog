run_hook_cmd() {  # run_hook_cmd <expected> <description> <project dir>
  local actual
  (cd "$branch_dir" && bash_json 'git status' 2>/dev/null | CLAUDE_PROJECT_DIR="$3" sh -c "$hook_cmd" >/dev/null 2>&1); actual=$?
  if [[ "$actual" == "$1" ]]; then echo "  ok    [$actual] $2"; else echo "  FAIL  [$actual, expected $1] $2"; failures=$((failures + 1)); fi
}
